int get_font_index(char c) {
    if (c >= ' ' && c <= 'Z') {
        return c - ' ';
    }
    return -1;
}

const unsigned char* get_bitmap(char c) {
    int idx = get_font_index(c);
    if (idx < 0) return nullptr;
    return minecraft_font[idx];
}
